#!/usr/bin/env python3
"""Regenerate the Sequoia IO80211InfraProtocol fail-closed ABI skeleton.

The private reference headers are supplied by the caller, never vendored here.
This only copies method signatures; no third-party implementation is used.
"""

import argparse
from pathlib import Path
import re


METHOD = re.compile(r"^\s*virtual IOReturn (\w+)\(([^()]*)\) = 0;\s*$")
EXPECTED_METHODS = 190
IMPLEMENTED_SEPARATELY = {"setWCL_SCAN_REQ"}


def generate(header: Path) -> str:
    methods = []
    for line in header.read_text().splitlines():
        match = METHOD.fullmatch(line)
        if match:
            methods.append((match.group(1), match.group(2)))
    if len(methods) != EXPECTED_METHODS or len(set(methods)) != len(methods):
        raise ValueError(f"expected {EXPECTED_METHODS} distinct IOReturn methods, found {len(methods)}")
    lines = [
        "// Generated by tools/generate_native_protocol_stubs.py from the macOS 15 reference.",
        "// Fail closed: these callbacks are not a functional Wi-Fi/AWDL implementation.",
    ]
    for name, argument in methods:
        if name in IMPLEMENTED_SEPARATELY:
            continue
        lines.append(
            f"    IOReturn {name}({argument}) override {{ return kIOReturnUnsupported; }}"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the generated file is stale")
    parser.add_argument("header", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    content = generate(args.header)
    if args.check:
        if not args.output.exists() or args.output.read_text() != content:
            parser.error(f"{args.output} is stale for {args.header}")
    else:
        args.output.write_text(content)


if __name__ == "__main__":
    main()
